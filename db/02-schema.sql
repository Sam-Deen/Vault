CREATE TABLE organizations (id bigint PRIMARY KEY, name text NOT NULL);
CREATE TABLE users (
  id bigint PRIMARY KEY, username text NOT NULL UNIQUE, "passwordHash" text NOT NULL,
  "organizationId" bigint NOT NULL REFERENCES organizations(id), role text NOT NULL,
  "totpSecret" text, "pendingTotpSecret" text
);
CREATE TABLE documents (
  id bigint PRIMARY KEY, "organizationId" bigint NOT NULL REFERENCES organizations(id),
  "ownerId" bigint NOT NULL REFERENCES users(id), filename text NOT NULL,
  content text NOT NULL, "createdAt" text NOT NULL, version integer NOT NULL,
  iv text NOT NULL, "authTag" text NOT NULL
);
CREATE TABLE permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "documentId" bigint NOT NULL REFERENCES documents(id), "userId" bigint NOT NULL REFERENCES users(id),
  permission text NOT NULL CHECK (permission IN ('READ', 'WRITE', 'MANAGE')),
  UNIQUE ("documentId", "userId")
);
CREATE TABLE document_keys (
  "documentId" bigint NOT NULL REFERENCES documents(id), version integer NOT NULL,
  "wrappedKey" text NOT NULL, iv text NOT NULL, "authTag" text NOT NULL,
  PRIMARY KEY ("documentId", version)
);
