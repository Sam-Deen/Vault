-- IF NOT EXISTS supports adoption of the preserved Hibernate demonstration schema.
CREATE TABLE IF NOT EXISTS organizations (id bigint PRIMARY KEY, name varchar(255) NOT NULL);
CREATE TABLE IF NOT EXISTS vault_users (
 id bigint PRIMARY KEY, username varchar(255) NOT NULL UNIQUE, password_hash varchar(255) NOT NULL,
 organization_id bigint NOT NULL REFERENCES organizations(id), role varchar(255) NOT NULL);
CREATE TABLE IF NOT EXISTS documents (
 id bigint PRIMARY KEY, organization_id bigint NOT NULL REFERENCES organizations(id),
 owner_id bigint NOT NULL REFERENCES vault_users(id), filename varchar(255) NOT NULL,
 content text NOT NULL, created_at timestamp(6) with time zone NOT NULL);
CREATE TABLE IF NOT EXISTS document_permissions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id bigint NOT NULL REFERENCES documents(id), user_id bigint NOT NULL REFERENCES vault_users(id),
 permission varchar(255) NOT NULL, UNIQUE(document_id, user_id));
